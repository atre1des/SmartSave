// Firebase Service for SmartSave
// Handles Firebase initialization and provides graceful error handling

import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';

/// Result of Firebase initialization
enum FirebaseInitStatus {
  /// Firebase initialized successfully
  initialized,
  /// Firebase initialization failed (configuration missing, network error, etc.)
  failed,
  /// Firebase is not configured (no google-services.json / GoogleService-Info.plist)
  notConfigured,
}

/// Service for managing Firebase initialization
class FirebaseService {
  FirebaseService._();
  static final FirebaseService instance = FirebaseService._();

  /// Current initialization status
  FirebaseInitStatus _status = FirebaseInitStatus.notConfigured;
  String? _errorMessage;

  /// Get current initialization status
  FirebaseInitStatus get status => _status;

  /// Get error message if initialization failed
  String? get errorMessage => _errorMessage;

  /// Check if Firebase is initialized and ready
  bool get isInitialized => _status == FirebaseInitStatus.initialized;

  /// Initialize Firebase with graceful error handling
  ///
  /// Returns true if Firebase was initialized successfully, false otherwise.
  /// Never throws - all errors are caught and logged.
  Future<bool> initialize() async {
    try {
      // Check if Firebase is already initialized
      if (Firebase.apps.isNotEmpty) {
        _status = FirebaseInitStatus.initialized;
        debugPrint('[FirebaseService] Firebase already initialized');
        return true;
      }

      // Attempt to initialize Firebase
      // This will automatically use firebase_options.dart if generated by flutterfire configure,
      // or fall back to platform defaults if configuration files are present
      await Firebase.initializeApp();

      _status = FirebaseInitStatus.initialized;
      debugPrint('[FirebaseService] Firebase initialized successfully');
      return true;
    } on FirebaseException catch (e) {
      _status = FirebaseInitStatus.failed;
      _errorMessage = 'Firebase initialization failed: $e.message (code: $e.code)';
      debugPrint('[FirebaseService] $_errorMessage');
      return false;
    } catch (e, stackTrace) {
      _status = FirebaseInitStatus.failed;
      _errorMessage = 'Unexpected error during Firebase initialization: $e';
      debugPrint('[FirebaseService] $_errorMessage\n$stackTrace');
      return false;
    }
  }

  /// Check if Firebase configuration files exist
  ///
  /// This is a best-effort check. On Android, checks for google-services.json.
  /// On iOS, checks for GoogleService-Info.plist.
  /// Note: This only works on the actual platform, not in emulators/simulators
  /// without proper configuration.
  Future<bool> hasConfiguration() async {
    try {
      // Try to initialize with default options - if it fails due to missing config,
      // we'll catch it in the main initialize() method
      final options = Firebase.app().options;
      return options.apiKey.isNotEmpty;
    } catch (_) {
      return false;
    }
  }

  /// Reset the service state (useful for testing)
  void reset() {
    _status = FirebaseInitStatus.notConfigured;
    _errorMessage = null;
  }
}

/// Convenience function to get the Firebase service instance
FirebaseService get firebaseService => FirebaseService.instance;